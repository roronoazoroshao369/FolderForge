export interface DashboardOptions {
  host: string;
  port: number;
  /**
   * Bearer token required on every request when the bind host is NOT loopback.
   * Loopback binds (127.0.0.1, ::1, localhost) skip auth. If omitted for a
   * non-loopback bind, one is generated by the caller.
   */
  token?: string;
  /**
   * Force credential auth even on a loopback bind (Mission Control control
   * plane started with `--auth token|api-key`). Defaults to the historic
   * behavior: required only for non-loopback binds.
   */
  requireAuth?: boolean;
}

/** True when the bind host is loopback-only and therefore safe without a token. */
export function isLoopbackHost(host: string): boolean {
  return host === "127.0.0.1" || host === "::1" || host === "localhost";
}

/**
 * Local control-plane dashboard. Read-only views plus approval actions.
 *
 * Endpoints:
 *   GET  /            -> 308 redirect to /app/ (Mission Control SPA)
 *   GET  /app         -> Mission Control SPA (packages/mission-control build, when present)
 *   GET  /status      -> server + workspace + policy snapshot
 *   GET  /audit       -> recent audit events
 *   GET  /processes   -> managed long-running processes
 *   GET  /approvals   -> pending + resolved approval requests
 *   POST /approvals/:id/approve  -> approve (body: { scope?: 'once'|'session' })
 *   POST /approvals/:id/deny     -> deny
 *   POST /policy/mode             -> change runtime policy mode (admin only)
 *   GET  /fleet                    -> provisioned per-folder MCP instances
 *   POST /fleet                    -> provision a folder (preset/policy + none|token|api-key|oauth auth)
 *   POST /fleet/:id/start|stop|restart -> local instance lifecycle (governed via provision_* tools)
 *   POST /fleet/:id/auto-restart   -> toggle auto-restart (body: { enabled: boolean })
 *   POST /fleet/:id/preset         -> change tool preset (body: { toolsPreset }); applies on next start
 *   POST /fleet/:id/policy         -> change policy mode (body: { policyMode }); applies on next start
 *   POST /fleet/:id/auth           -> change authentication mode; static credentials returned once
 *   POST /fleet/:id/rotate-token|rotate-credential -> rotate static credentials (HIGH; returned once)
 *   POST /fleet/:id/tunnel         -> expose an authenticated running instance via Cloudflare (HIGH)
 *   POST /fleet/:id/openai-tunnel/start|stop -> supervise OpenAI Secure MCP Tunnel lifecycle
 *   GET  /fleet/:id/openai-tunnel/logs -> redacted OpenAI tunnel supervisor output
 *   GET  /fleet/:id/logs           -> non-consuming tail of the local instance process log
 *   GET  /tools                    -> tool catalog with groups, risk, and preset coverage
 *   GET  /plugins                  -> installed plugins (via plugin_list)
 *   GET  /marketplace              -> marketplace index entries (via marketplace_list)
 *   POST /plugins/:id/enable|disable -> plugin lifecycle (governed via plugin_enable/disable)
 *   GET  /workspaces               -> activated workspaces (via workspace_list)
 *   POST /workspaces/switch        -> switch current workspace (body: { path })
 *   POST /workspaces/activate      -> activate a folder as a workspace (body: { path })
 *   POST /fs/browse                -> list subdirectories under the widest governable dir (body: { path? })
 *   POST /fs/mkdir                 -> create a directory under that same bound (body: { path, name })
 *   GET  /tunnels                  -> quick tunnels (via tunnel_list)
 *   POST /tunnels                  -> expose a port publicly (body: { targetPort }) HIGH risk
 *   POST /tunnels/:id/stop         -> close a tunnel; body { cleanup: true } also deletes the Cloudflare DNS record + tunnel for named ones
 *   GET  /cloudflare/status        -> linked Cloudflare account (masked; the token is never returned)
 *   POST /cloudflare/config        -> link an account: { apiToken, accountId, domain } (token verified, zone resolved, stored 0600)
 *   DELETE /cloudflare/config      -> unlink the account
 *   GET  /openai-tunnel/status     -> saved ChatGPT tunnel config (env-var NAME only) + supervisor state
 *   POST /openai-tunnel/config     -> save tunnel id + API-key env name (0600; no secret values)
 *   DELETE /openai-tunnel/config   -> unlink the ChatGPT tunnel config
 *   POST /openai-tunnel/start|stop -> supervise the ChatGPT tunnel from the app (OpenAI instead of Cloudflare)
 */
export function startDashboard(
  container: Container,
  registry: ToolRegistry,
  opts: DashboardOptions,
): HttpServer {
  // Auth is enforced only when bound to a non-loopback address, unless the
  // caller explicitly requires it (control plane with --auth token|api-key).
  const requireAuth = opts.requireAuth ?? !isLoopbackHost(opts.host);
  if (requireAuth && !opts.token) {
    throw new Error("Dashboard bound to a non-loopback host requires a token");
  }

  const server = createServer((req, res) => {
    const credential = extractDashboardCredential(req);
    if (
      requireAuth &&
      (!credential || !timingSafeEqualStr(credential, opts.token!))
    ) {
      res.writeHead(401, {
        "content-type": "application/json; charset=utf-8",
        "www-authenticate": 'Bearer realm="folderforge-dashboard"',
      });
      res.end(
        JSON.stringify({
          error: "unauthorized",
          message: "Valid bearer token required.",
        }),
      );
      return;
    }
    const principal = adminPrincipalFromCredential(
      requireAuth ? credential : undefined,
    );
    handle(req, res, container, registry, principal).catch((err) => {
      logger.error({ err: String(err) }, "Dashboard request failed");
      sendJson(res, 500, { error: "internal_error", message: String(err) });
    });
  });

  server.listen(opts.port, opts.host, () => {
    logger.info(
      { host: opts.host, port: opts.port, authRequired: requireAuth },
      "Dashboard listening",
    );
  });

  return server;
}

/**
 * Accept the credential via `Authorization: Bearer <cred>`, an `X-API-Key`
 * header (api-key mode), or a `?token=` query parameter (handy for opening the
 * dashboard in a browser). Comparison is constant-time to avoid leaking the
 * credential length/prefix via timing.
 */
function extractDashboardCredential(req: IncomingMessage): string | undefined {
  const header = req.headers["authorization"];
  if (typeof header === "string" && header.startsWith("Bearer ")) {
    const credential = header.slice("Bearer ".length).trim();
    if (credential) return credential;
  }
  // `api-key` mode: the same credential delivered via the X-API-Key header.
  const apiKey = req.headers["x-api-key"];
  if (typeof apiKey === "string" && apiKey.trim()) return apiKey.trim();
  const url = new URL(req.url ?? "/", "http://localhost");
  return url.searchParams.get("token") ?? undefined;
}

/** All directories the operator lets this control plane govern (resolved). */
function fsAllowedRoots(container: Container): string[] {
  const dirs = container.config.workspace.allowedDirectories ?? [];
  if (dirs.length > 0) return dirs.map((d) => resolve(d));
  try {
    return [defaultBrowsePoint()];
  } catch {
    return [container.projectRoot()];
  }
}

/** Display root for the SPA picker: the primary governable directory. */
function fsBrowsePoint(container: Container): string {
  return fsAllowedRoots(container)[0] ?? container.projectRoot();
}

/** Best-effort default: ~/Desktop when it exists, else the home directory. */
function defaultBrowsePoint(): string {
  const desktop = join(homedir(), "Desktop");
  return existsSync(desktop) && statSync(desktop).isDirectory() ? desktop : homedir();
}

/** True when `target` equals or sits inside `root`. */
function isWithinDir(root: string, target: string): boolean {
  const from = resolve(root);
  const to = resolve(target);
  return to === from || to.startsWith(from + sep);
}

/**
 * Serve the Mission Control SPA (built from packages/mission-control) under
 * /app. Prefers the packaged build output (dist/dashboard/app) and falls back
 * to the in-repo package dist when running from a checkout. 404 with build
 * instructions when the SPA has not been built.
 */
function serveMissionControlApp(res: ServerResponse, path: string): void {
  const relative = path === "/app" || path === "/app/" ? "index.html" : path.slice("/app/".length);
  if (relative.includes("..")) {
    res.writeHead(400, { "content-type": "text/plain" });
    res.end("bad path");
    return;
  }
  const roots = [
    join(__dirname, "app"),
    join(process.cwd(), "packages", "mission-control", "dist"),
  ];
  for (const rootDir of roots) {
    const file = join(rootDir, relative);
    if (existsSync(file) && statSync(file).isFile()) {
      const type = relative.endsWith(".js")
        ? "text/javascript"
        : relative.endsWith(".css")
          ? "text/css"
          : relative.endsWith(".svg")
            ? "image/svg+xml"
            : relative.endsWith(".json")
              ? "application/json"
              : "text/html; charset=utf-8";
      res.writeHead(200, { "content-type": type });
      res.end(readFileSync(file));
      return;
    }
  }
  // Client-side routes (e.g. /app/fleet) have no asset file: fall back to the SPA shell.
  if (!/\.[a-z0-9]+$/i.test(relative)) {
    for (const rootDir of roots) {
      const file = join(rootDir, "index.html");
      if (existsSync(file) && statSync(file).isFile()) {
        res.writeHead(200, { "content-type": "text/html; charset=utf-8" });
        res.end(readFileSync(file));
        return;
      }
    }
  }
  res.writeHead(404, { "content-type": "text/plain" });
  res.end(
    "Mission Control app not built. Run: npm --prefix packages/mission-control install && npm run build:mission-control",
  );
}

function timingSafeEqualStr(a: string, b: string): boolean {
  const ab = Buffer.from(a);
  const bb = Buffer.from(b);
  if (ab.length !== bb.length) return false;
  return timingSafeEqual(ab, bb);
}

